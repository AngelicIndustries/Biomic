package industries.angelic.biomic.biome.placement;

/**
 * Reusable terrain slots selected before a named surface biome. Island membership is deliberately
 * orthogonal: a sufficiently large island can contain ordinary flat, rolling, slope, and peak slots.
 */
public enum SurfaceLandform {

    DEEP_OCEAN,
    OCEAN,
    SHALLOW_OCEAN,
    BEACH,
    ROCKY_SHORE,
    COASTAL_LOWLAND,
    VALLEY,
    FLAT,
    ROLLING,
    PLATEAU,
    SLOPE,
    PEAK,
    CLIFF,
    RIVER_BANK,
    RIVER_CHANNEL,
    WETLAND
}
