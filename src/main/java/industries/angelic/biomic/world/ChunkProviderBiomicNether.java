package industries.angelic.biomic.world;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

import net.minecraft.block.Block;
import net.minecraft.block.BlockFalling;
import net.minecraft.entity.EnumCreatureType;
import net.minecraft.init.Blocks;
import net.minecraft.util.IProgressUpdate;
import net.minecraft.world.ChunkPosition;
import net.minecraft.world.World;
import net.minecraft.world.biome.BiomeGenBase;
import net.minecraft.world.chunk.Chunk;
import net.minecraft.world.chunk.IChunkProvider;
import net.minecraft.world.chunk.storage.ExtendedBlockStorage;
import net.minecraft.world.gen.structure.MapGenNetherBridge;
import net.minecraftforge.common.MinecraftForge;
import net.minecraftforge.event.terraingen.InitMapGenEvent;
import net.minecraftforge.event.terraingen.PopulateChunkEvent;
import net.minecraftforge.event.terraingen.TerrainGen;

import industries.angelic.biomic.compat.endlessids.EndlessIdsBiomeStorage;
import industries.angelic.biomic.config.PerformanceConfig;
import industries.angelic.biomic.world.terrain.TartarusFeatures;
import industries.angelic.biomic.world.terrain.TartarusTerrainRuntime;

/**
 * The Tartarus Nether: the pack's terrain, palettes and features generated chunk by chunk at its authored 0..255,
 * whatever the storage height. Everything is computed ahead on worker threads; the server thread only maps states to
 * blocks.
 */
public final class ChunkProviderBiomicNether implements IChunkProvider, BenchmarkedChunkProvider, TerrainPrefetching {

    private static final int HEIGHT = TartarusTerrainRuntime.SOURCE_MAX_Y - TartarusTerrainRuntime.SOURCE_MIN_Y;

    private final World world;
    private final WorldChunkManagerBiomicNether biomes;
    private final NetherStates states = new NetherStates();
    private final NetherTerrainSource terrain;
    private final TerrainPrecomputeScheduler terrainPrecompute;
    private final WorldgenPerformanceTracker performance = new WorldgenPerformanceTracker();
    private final boolean mapFeaturesEnabled;
    /** Vanilla fortresses in Tartarus' open caverns (TartarusFortresses); mods may still swap the generator. */
    private final MapGenNetherBridge fortresses;
    private final NetherFood food;
    private final NetherTrees trees;

    public ChunkProviderBiomicNether(World world) {
        if (!(world.getWorldChunkManager() instanceof WorldChunkManagerBiomicNether manager))
            throw new IllegalStateException("The Tartarus Nether needs its own chunk manager");
        this.world = world;
        biomes = manager;
        terrain = new NetherTerrainSource(
            manager.rasterizer(),
            TartarusFeatures.load(manager.manifest(), world.getSeed()),
            states,
            world.getSeed(),
            manager.gardens(),
            manager.ru());
        mapFeaturesEnabled = world.getWorldInfo()
            .isMapFeaturesEnabled();
        fortresses = (MapGenNetherBridge) TerrainGen
            .getModdedMapGen(new TartarusFortresses(terrain, world.getSeed()), InitMapGenEvent.EventType.NETHER_BRIDGE);
        food = new NetherFood(world.getSeed());
        trees = new NetherTrees(world.getSeed());
        terrainPrecompute = new TerrainPrecomputeScheduler(
            this::computeTerrain,
            PerformanceConfig.terrainWorkerThreads,
            PerformanceConfig.terrainPrefetchTasks);
        // Every mod has registered its spawns by the time a server builds its worlds.
        industries.angelic.biomic.biome.TartarusSpawns.apply();
        declareLogicalHeight(world);
    }

    /**
     * Portals search and build within the dimension's logical height, which Nether providers report as 128. Hohen
     * Angst owns that figure; tell it the Tartarus Nether fills 0..255. Without Hohen Angst portals stay below 128.
     */
    private static void declareLogicalHeight(World world) {
        if (!cpw.mods.fml.common.Loader.isModLoaded("hohenangst")) return;
        try {
            Class.forName("industries.angelic.hohenangst.api.LogicalHeights")
                .getMethod("set", World.class, int.class)
                .invoke(null, world, HEIGHT);
            industries.angelic.biomic.Biomic.LOG.info("Tartarus Nether logical height: {}", world.getActualHeight());
        } catch (ClassNotFoundException older) {
            industries.angelic.biomic.Biomic.LOG
                .warn("Hohen Angst has no logical heights; Nether portals stay below 128");
        } catch (ReflectiveOperationException error) {
            throw new IllegalStateException("Cannot set the Tartarus Nether's logical height", error);
        }
    }

    /** Whether a world is the Tartarus Nether generated by this provider. */
    public static boolean generates(World world) {
        return world instanceof net.minecraft.world.WorldServer server && server.theChunkProviderServer != null
            && server.theChunkProviderServer.currentChunkProvider instanceof ChunkProviderBiomicNether;
    }

    /** Worker-safe. Materials hold state ids at (x*16+z)*256+y; the authored slot holds each column's biome. */
    private TerrainPrecomputeScheduler.TerrainPayload computeTerrain(int chunkX, int chunkZ) {
        // Fortress plans read the pure terrain of a whole layout: make them here, not on the server thread.
        if (mapFeaturesEnabled && fortresses instanceof TartarusFortresses planned) planned.prepare(chunkX, chunkZ);
        byte[] materials = terrain.chunk(chunkX, chunkZ);
        byte[] columnBiomes = new byte[EndlessIdsBiomeStorage.ENTRY_COUNT];
        for (int z = 0; z < 16; z++) for (int x = 0; x < 16; x++)
            columnBiomes[z * 16 + x] = (byte) biomes.biomeIndexAt(chunkX * 16 + x, chunkZ * 16 + z);
        return new TerrainPrecomputeScheduler.TerrainPayload(
            null,
            materials,
            columnBiomes,
            null,
            terrain.blockLight(materials));
    }

    @Override
    public boolean chunkExists(int chunkX, int chunkZ) {
        return true;
    }

    @Override
    public Chunk provideChunk(int chunkX, int chunkZ) {
        long startedAt = System.nanoTime();
        var payload = terrainPrecompute.take(chunkX, chunkZ);
        long precomputedAt = System.nanoTime();
        byte[] materials = payload.getMaterials();
        Block[] blockById = states.blocks();
        byte[] metadataById = states.metadata();
        Chunk chunk = new Chunk(world, chunkX, chunkZ);
        ExtendedBlockStorage[] sections = chunk.getBlockStorageArray();
        for (int x = 0; x < 16; x++) for (int z = 0; z < 16; z++) {
            int column = (x * 16 + z) * HEIGHT;
            for (int y = 0; y < HEIGHT; y++) {
                int id = materials[column + y] & 255;
                Block block = blockById[id];
                if (block == Blocks.air) continue;
                ExtendedBlockStorage section = sections[y >> 4];
                if (section == null)
                    sections[y >> 4] = section = new ExtendedBlockStorage(y & ~15, !world.provider.hasNoSky);
                section.func_150818_a(x, y & 15, z, block);
                section.setExtBlockMetadata(x, y & 15, z, metadataById[id]);
            }
        }
        byte[] light = payload.getBlockLight();
        for (int i = 0; i < light.length; i++) {
            if (light[i] == 0) continue;
            int y = i & 255, z = i >> 8 & 15, x = i >> 12;
            ExtendedBlockStorage section = sections[y >> 4];
            // Light in an all-air section has nowhere to live; vanilla's relight checks fill it in if blocks arrive.
            if (section != null) section.setExtBlocklightValue(x, y & 15, z, light[i]);
        }
        long chunkConstructedAt = System.nanoTime();
        byte[] columnBiomes = payload.getAuthoredMaterials();
        int[] biomeIds = new int[EndlessIdsBiomeStorage.ENTRY_COUNT];
        for (int i = 0; i < biomeIds.length; i++) biomeIds[i] = biomes.biome(columnBiomes[i]).biomeID;
        EndlessIdsBiomeStorage.setBiomeIds(chunk, biomeIds);
        chunk.resetRelightChecks();
        if (mapFeaturesEnabled) fortresses.func_151539_a(this, world, chunkX, chunkZ, null);
        long completedAt = System.nanoTime();
        performance.recordTerrain(
            precomputedAt - startedAt,
            0,
            0,
            chunkConstructedAt - precomputedAt,
            completedAt - chunkConstructedAt,
            0,
            completedAt - startedAt);
        return chunk;
    }

    @Override
    public Chunk loadChunk(int chunkX, int chunkZ) {
        return provideChunk(chunkX, chunkZ);
    }

    @Override
    public void populate(IChunkProvider chunkProvider, int chunkX, int chunkZ) {
        long startedAt = System.nanoTime();
        Random random = new Random(world.getSeed() ^ chunkX * 341873128712L ^ chunkZ * 132897987541L);
        boolean previousFallInstantly = BlockFalling.fallInstantly;
        BlockFalling.fallInstantly = true;
        try {
            MinecraftForge.EVENT_BUS
                .post(new PopulateChunkEvent.Pre(chunkProvider, world, random, chunkX, chunkZ, false));
            if (mapFeaturesEnabled) fortresses.generateStructuresInChunk(world, random, chunkX, chunkZ);
            // Other mods dress their own biomes; as in vanilla, the area takes the biome at its centre.
            int centre = biomes.biomeIndexAt(chunkX * 16 + 16, chunkZ * 16 + 16);
            NetherNeighbour neighbour = biomes.neighbour(centre);
            if (neighbour != null)
                NetherNeighbourDressing.dress(world, neighbour, biomes.biome(centre), chunkX, chunkZ);
            food.populate(world, chunkX, chunkZ);
            trees.populate(world, chunkX, chunkZ);
            MinecraftForge.EVENT_BUS
                .post(new PopulateChunkEvent.Post(chunkProvider, world, random, chunkX, chunkZ, false));
        } finally {
            BlockFalling.fallInstantly = previousFallInstantly;
            long completedAt = System.nanoTime();
            performance.recordPopulation(0, 0, 0, completedAt - startedAt, 0, 0, completedAt - startedAt);
        }
    }

    @Override
    public List<String> getPerformanceReport() {
        List<String> report = new ArrayList<>(performance.report());
        report.add(terrainPrecompute.performanceReport());
        report.add(terrain.report());
        report.add(food.report());
        report.add(trees.report());
        return report;
    }

    @Override
    public void resetPerformanceStats() {
        performance.reset();
        terrainPrecompute.resetPerformanceStats();
    }

    public void shutdownTerrainPrecompute() {
        terrainPrecompute.shutdown();
    }

    @Override
    public boolean saveChunks(boolean saveAll, IProgressUpdate progress) {
        return true;
    }

    @Override
    public boolean unloadQueuedChunks() {
        return false;
    }

    @Override
    public boolean canSave() {
        return true;
    }

    @Override
    public String makeString() {
        return "BiomicTartarusLevelSource";
    }

    @Override
    public List<BiomeGenBase.SpawnListEntry> getPossibleCreatures(EnumCreatureType creatureType, int blockX, int blockY,
        int blockZ) {
        if (creatureType == EnumCreatureType.monster
            && (fortresses.hasStructureAt(blockX, blockY, blockZ) || fortresses.func_142038_b(blockX, blockY, blockZ)
                && world.getBlock(blockX, blockY - 1, blockZ) == Blocks.nether_brick))
            return fortresses.getSpawnList();
        return world.getBiomeGenForCoords(blockX, blockZ)
            .getSpawnableList(creatureType);
    }

    @Override
    public ChunkPosition func_147416_a(World queryWorld, String structureName, int blockX, int blockY, int blockZ) {
        return mapFeaturesEnabled && "Fortress".equals(structureName)
            ? fortresses.func_151545_a(queryWorld, blockX, blockY, blockZ)
            : null;
    }

    @Override
    public int getLoadedChunkCount() {
        return 0;
    }

    @Override
    public void recreateStructures(int chunkX, int chunkZ) {
        if (mapFeaturesEnabled) fortresses.func_151539_a(this, world, chunkX, chunkZ, null);
    }

    @Override
    public void saveExtraData() {}

    @Override
    public boolean prefetchTerrain(int chunkX, int chunkZ) {
        return terrainPrecompute.prefetchAhead(chunkX, chunkZ);
    }

    @Override
    public boolean terrainReady(int chunkX, int chunkZ) {
        return terrainPrecompute.ready(chunkX, chunkZ);
    }
}
